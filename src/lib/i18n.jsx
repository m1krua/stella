const defaultLanguageContext = { language: 'ru', setLanguage: () => {}, isEnglish: false, t: (text) => text }
const LanguageContext = createContext(defaultLanguageContext)

export function LanguageProvider({ children }) {
  const [language, setLanguage] = useState(() => localStorage.getItem('stella-language') || 'ru')
  useEffect(() => {
    localStorage.setItem('stella-language', language)
    document.documentElement.lang = language
  }, [language])
  useEffect(() => {
    const reverseTranslations = Object.fromEntries(Object.entries(translations).map(([source, translated]) => [translated, source]))
    const translate = (value) => {
      const entries = Object.entries(language === 'en' ? translations : reverseTranslations)
        .filter(([source]) => source && value.includes(source))
        .sort(([a], [b]) => b.length - a.length)
      return entries.reduce((result, [source, target]) => result.split(source).join(target), value)
    }
    const translateTextNodes = () => {
      const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT)
      const nodes = []
      let node = walker.nextNode()
      while (node) { nodes.push(node); node = walker.nextNode() }
      nodes.forEach(textNode => {
        const value = textNode.nodeValue.trim()
        if (!value) return
        const translated = translate(textNode.nodeValue)
        if (translated !== textNode.nodeValue) textNode.nodeValue = translated
      })
      document.querySelectorAll('[placeholder], [aria-label], [title]').forEach(element => {
        for (const attribute of ['placeholder', 'aria-label', 'title']) {
          if (element.hasAttribute(attribute)) {
            const value = element.getAttribute(attribute)
            const translated = translate(value)
            if (translated !== value) element.setAttribute(attribute, translated)
          }
        }
      })
    }
    translateTextNodes()
    const observer = new MutationObserver(translateTextNodes)
    observer.observe(document.body, { childList: true, subtree: true })
    return () => observer.disconnect()
  }, [language])
  const value = { language, setLanguage, isEnglish: language === 'en', t: (text) => language === 'en' ? translations[text] || text : text }
  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>
}

export function useLanguage() {
  return useContext(LanguageContext) || defaultLanguageContext
}
